USE ROLE SYSADMIN;
USE WAREHOUSE PSET2_WH;

-- La salida final del modelo queda en Snowflake.
SELECT
    COUNT(*) AS TOTAL_FILAS,
    COUNT(DISTINCT CUSTOMER_ID) AS CLIENTES_UNICOS,
    COUNT_IF(CHURN_FLAG = 1) AS ABANDONARON,
    COUNT_IF(TOTAL_CHARGES IS NULL) AS TOTAL_CHARGES_NULOS
FROM PSET2_CHURN.OBT.CUSTOMER_CHURN_OBT;

-- Sin filas duplicadas por cliente:
SELECT CUSTOMER_ID, COUNT(*) AS VECES
FROM PSET2_CHURN.OBT.CUSTOMER_CHURN_OBT
GROUP BY CUSTOMER_ID
HAVING COUNT(*) > 1;

-- Comparación de cardinalidad Gold contra OBT:
SELECT
    (SELECT COUNT(*) FROM PSET2_CHURN.GOLD.FACT_CUSTOMER_CHURN) AS HECHOS_GOLD,
    (SELECT COUNT(*) FROM PSET2_CHURN.OBT.CUSTOMER_CHURN_OBT) AS FILAS_OBT;
