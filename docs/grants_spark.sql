-- Ejecutar como SECURITYADMIN con permisos administrativos suficientes.
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS PSET2_SPARK_ROLE;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_SPARK_ROLE;
GRANT USAGE ON DATABASE PSET2_CHURN TO ROLE PSET2_SPARK_ROLE;
GRANT USAGE ON SCHEMA PSET2_CHURN.GOLD TO ROLE PSET2_SPARK_ROLE;
GRANT USAGE ON SCHEMA PSET2_CHURN.OBT TO ROLE PSET2_SPARK_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA PSET2_CHURN.GOLD TO ROLE PSET2_SPARK_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PSET2_CHURN.GOLD TO ROLE PSET2_SPARK_ROLE;
-- El Spark Connector utiliza stages internos temporales al leer y escribir.
GRANT CREATE STAGE ON SCHEMA PSET2_CHURN.GOLD TO ROLE PSET2_SPARK_ROLE;
GRANT CREATE STAGE ON SCHEMA PSET2_CHURN.OBT TO ROLE PSET2_SPARK_ROLE;
-- Escritura de la tabla OBT y staging table temporal de seguridad.
GRANT CREATE TABLE ON SCHEMA PSET2_CHURN.OBT TO ROLE PSET2_SPARK_ROLE;
GRANT ROLE PSET2_SPARK_ROLE TO USER PSET2_KESTRA_SVC;
-- Poder consultar las tablas que Spark cree desde SYSADMIN.
GRANT SELECT ON FUTURE TABLES IN SCHEMA PSET2_CHURN.OBT TO ROLE SYSADMIN;
