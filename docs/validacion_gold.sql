-- Ejecutar en Snowflake bajo rol con SELECT sobre Gold.
USE ROLE SECURITYADMIN;
GRANT USAGE ON SCHEMA PSET2_CHURN.GOLD TO ROLE SYSADMIN;
GRANT SELECT ON ALL TABLES IN SCHEMA PSET2_CHURN.GOLD TO ROLE SYSADMIN;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PSET2_CHURN.GOLD TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
USE WAREHOUSE PSET2_WH;

SELECT 'DIM_CUSTOMER' AS OBJETO, COUNT(*) AS FILAS FROM PSET2_CHURN.GOLD.DIM_CUSTOMER
UNION ALL
SELECT 'DIM_CONTRACT', COUNT(*) FROM PSET2_CHURN.GOLD.DIM_CONTRACT
UNION ALL
SELECT 'DIM_SERVICES', COUNT(*) FROM PSET2_CHURN.GOLD.DIM_SERVICES
UNION ALL
SELECT 'FACT_CUSTOMER_CHURN', COUNT(*) FROM PSET2_CHURN.GOLD.FACT_CUSTOMER_CHURN;

SELECT COUNT(*) AS JOIN_FILAS,
       COUNT(DISTINCT f.CUSTOMER_ID) AS CLIENTES_UNICOS,
       SUM(f.CHURN_FLAG) AS ABANDONARON,
       COUNT_IF(f.TOTAL_CHARGES IS NULL) AS TOTAL_CHARGES_NULOS
FROM PSET2_CHURN.GOLD.FACT_CUSTOMER_CHURN f
JOIN PSET2_CHURN.GOLD.DIM_CUSTOMER c USING (CUSTOMER_KEY)
JOIN PSET2_CHURN.GOLD.DIM_CONTRACT ct USING (CONTRACT_KEY)
JOIN PSET2_CHURN.GOLD.DIM_SERVICES s USING (SERVICES_KEY);
