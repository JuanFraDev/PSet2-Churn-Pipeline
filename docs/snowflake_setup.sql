-- Ejecutar una vez en Snowsight > Projects > Worksheets.
-- SYSADMIN suele tener permisos para crear bases de datos y warehouses.
-- Si no dispones de este rol, consulta al administrador.
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS PSET2_CHURN;

CREATE WAREHOUSE IF NOT EXISTS PSET2_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE SCHEMA IF NOT EXISTS PSET2_CHURN.RAW;
CREATE SCHEMA IF NOT EXISTS PSET2_CHURN.BRONZE;
CREATE SCHEMA IF NOT EXISTS PSET2_CHURN.SILVER;
CREATE SCHEMA IF NOT EXISTS PSET2_CHURN.GOLD;
CREATE SCHEMA IF NOT EXISTS PSET2_CHURN.OBT;

SHOW SCHEMAS IN DATABASE PSET2_CHURN;
SHOW WAREHOUSES LIKE 'PSET2_WH';

